package app

import (
	"fmt"
	"io"
	"strings"
)

const completionHelp = `usage: gate completion <bash|zsh|fish|pwsh>

Print a shell completion script for that shell to stdout.
`

const manHelp = `usage: gate man

Print the gate(1) man page to stdout.
`

func runCompletion(args []string, stdout, stderr io.Writer) Code {
	var shell string
	haveShell := false
	for _, a := range args {
		if a == "--help" || a == "-h" {
			fmt.Fprint(stdout, completionHelp)
			return Success
		}
		if haveShell {
			fmt.Fprintln(stderr, "gate: completion requires exactly one shell argument (bash, zsh, fish, or pwsh)")
			fmt.Fprint(stderr, completionHelp)
			return InvalidUsage
		}
		shell = a
		haveShell = true
	}
	if !haveShell {
		fmt.Fprintln(stderr, "gate: completion requires exactly one shell argument (bash, zsh, fish, or pwsh)")
		fmt.Fprint(stderr, completionHelp)
		return InvalidUsage
	}
	script, ok := completionScript(shell)
	if !ok {
		fmt.Fprintf(stderr, "gate: unknown shell %q; supported: bash, zsh, fish, pwsh\n", shell)
		fmt.Fprint(stderr, completionHelp)
		return InvalidUsage
	}
	_, _ = io.WriteString(stdout, script)
	return Success
}

func runMan(args []string, stdout, stderr io.Writer) Code {
	for _, a := range args {
		if a == "--help" || a == "-h" {
			fmt.Fprint(stdout, manHelp)
			return Success
		}
	}
	if len(args) != 0 {
		fmt.Fprintln(stderr, "gate: man takes no arguments")
		fmt.Fprint(stderr, manHelp)
		return InvalidUsage
	}
	_, _ = io.WriteString(stdout, manPage())
	return Success
}

func completionScript(shell string) (string, bool) {
	cmds := strings.Join(completionCommands(), " ")
	flags := strings.Join(helpFlagTokens(gateHelp), " ")
	switch shell {
	case "bash":
		return bashCompletion(cmds, flags), true
	case "zsh":
		return zshCompletion(cmds, flags), true
	case "fish":
		return fishCompletion(completionCommands(), helpFlagTokens(gateHelp)), true
	case "pwsh":
		return pwshCompletion(cmds, flags), true
	default:
		return "", false
	}
}

// completionCommands is every word a first token can claim, including the
// hidden completion and man generators. Visible names come from --help so a
// new Commands: row cannot ship without appearing in every script.
func completionCommands() []string {
	return append(helpCommands(gateHelp), "completion", "man")
}

func helpCommands(help string) []string {
	_, after, ok := strings.Cut(help, "Commands:\n")
	if !ok {
		return nil
	}
	rest := after
	if end := strings.Index(rest, "\n\n"); end >= 0 {
		rest = rest[:end]
	}
	var names []string
	for line := range strings.SplitSeq(rest, "\n") {
		fields := strings.Fields(line)
		if len(fields) == 0 || strings.HasPrefix(fields[0], "<") {
			continue
		}
		names = append(names, fields[0])
	}
	return names
}

// helpFlagTokens is every flag spelling --help documents, including both
// sides of `-q, --quiet`. Completions read this so they cannot offer a flag
// the help does not, or miss one it does.
func helpFlagTokens(help string) []string {
	var flags []string
	for line := range strings.SplitSeq(help, "\n") {
		trimmed := strings.TrimLeft(line, " ")
		if len(line)-len(trimmed) != 2 || !strings.HasPrefix(trimmed, "-") {
			continue
		}
		for _, tok := range strings.FieldsFunc(trimmed, func(r rune) bool {
			return r == ' ' || r == ','
		}) {
			if !strings.HasPrefix(tok, "-") {
				break
			}
			flags = append(flags, tok)
		}
	}
	return flags
}

func bashCompletion(cmds, flags string) string {
	return `# gate bash completion -- generated by ` + "`gate completion bash`" + `.
_gate() {
    local cur prev
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"
    if [[ "$prev" == "-C" || "$prev" == "--log" ]]; then
        COMPREPLY=( $(compgen -f -- "$cur") )
        return 0
    fi
    if [[ "$prev" == "completion" ]]; then
        COMPREPLY=( $(compgen -W "bash zsh fish pwsh" -- "$cur") )
        return 0
    fi
    if [[ "$cur" == -* ]]; then
        COMPREPLY=( $(compgen -W "` + flags + `" -- "$cur") )
        return 0
    fi
    COMPREPLY=( $(compgen -W "` + cmds + `" -- "$cur") )
}
complete -F _gate gate
`
}

func zshCompletion(cmds, flags string) string {
	return `#compdef gate
# gate zsh completion -- generated by ` + "`gate completion zsh`" + `.
_gate() {
    local cur prev
    cur="${words[CURRENT]}"
    prev="${words[CURRENT-1]}"
    if [[ "$prev" == "-C" || "$prev" == "--log" ]]; then
        _files
        return
    fi
    if [[ "$prev" == "completion" ]]; then
        compadd -- bash zsh fish pwsh
        return
    fi
    if [[ "$cur" == -* ]]; then
        compadd -- ` + flags + `
        return
    fi
    compadd -- ` + cmds + `
}
(( $+functions[compdef] )) && compdef _gate gate
`
}

func fishCompletion(cmds, flags []string) string {
	var b strings.Builder
	b.WriteString("# gate fish completion -- generated by `gate completion fish`.\n")
	b.WriteString("complete -c gate -f\n")
	b.WriteString("complete -c gate -n '__fish_use_subcommand' -a '" + strings.Join(cmds, " ") + "'\n")
	b.WriteString("complete -c gate -n '__fish_seen_subcommand_from completion' -a 'bash zsh fish pwsh'\n")
	for _, flag := range flags {
		switch {
		case strings.HasPrefix(flag, "--"):
			b.WriteString("complete -c gate -l " + strings.TrimPrefix(flag, "--"))
		case strings.HasPrefix(flag, "-") && len(flag) == 2:
			b.WriteString("complete -c gate -s " + flag[1:])
		default:
			continue
		}
		if flag == "-C" || flag == "--log" {
			b.WriteString(" -r")
		}
		b.WriteByte('\n')
	}
	return b.String()
}

func pwshCompletion(cmds, flags string) string {
	return `# gate pwsh completion -- generated by ` + "`gate completion pwsh`" + `.
$gateCommands = '` + cmds + `'.Split(' ')
$gateFlags = '` + flags + `'.Split(' ')
Register-ArgumentCompleter -Native -CommandName gate -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $elements = @($commandAst.CommandElements)
    $prev = ''
    if ($elements.Count -ge 2) {
        $prev = [string]$elements[$elements.Count - 1].Extent.Text
        if ($elements[-1].Extent.EndOffset -ge $cursorPosition -and $elements.Count -ge 3) {
            $prev = [string]$elements[$elements.Count - 2].Extent.Text
        }
    }
    function Emit-Completion {
        param([string]$Text)
        if ($Text.StartsWith([string]$wordToComplete, [System.StringComparison]::OrdinalIgnoreCase)) {
            [System.Management.Automation.CompletionResult]::new($Text, $Text, 'ParameterValue', $Text)
        }
    }
    if ($prev -eq 'completion') {
        foreach ($shell in @('bash', 'zsh', 'fish', 'pwsh')) { Emit-Completion -Text $shell }
        return
    }
    if ($wordToComplete.StartsWith('-')) {
        foreach ($flag in $gateFlags) { Emit-Completion -Text $flag }
        return
    }
    foreach ($command in $gateCommands) { Emit-Completion -Text $command }
}
`
}

func manPage() string {
	var b strings.Builder
	b.WriteString(".TH GATE 1\n")
	b.WriteString(".SH NAME\n")
	b.WriteString("gate \\- run a project's gates and keep the complete log\n")
	b.WriteString(".SH DESCRIPTION\n.nf\n.na\n")
	for line := range strings.SplitSeq(gateHelp, "\n") {
		escaped := strings.ReplaceAll(line, `\`, `\\`)
		if strings.HasPrefix(escaped, ".") || strings.HasPrefix(escaped, "'") {
			escaped = `\&` + escaped
		}
		if escaped == "" {
			b.WriteString(".\n")
			continue
		}
		b.WriteString(escaped)
		b.WriteByte('\n')
	}
	b.WriteString(".ad\n.fi\n")
	return b.String()
}
